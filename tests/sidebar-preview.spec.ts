import { expect, test } from '@playwright/test'

test('selects Notes collections and independently folds groups with native keyboard controls', async ({ page }) => {
  await page.goto('/?lang=en#/desktop/sidebar')
  await expect(page.locator('.desktop-preview-card')).toHaveCount(4)
  const navigation = page.getByRole('region', { name: 'Sidebar Navigation', exact: true })
  const nav = navigation.getByRole('navigation', { name: 'Notes library' })
  await expect(nav.getByRole('button', { name: 'Starred', exact: true })).toHaveAttribute('aria-current', 'true')
  const personal = nav.getByRole('button', { name: 'Personal', exact: true })
  await personal.click()
  await expect(personal).toHaveAttribute('aria-current', 'true')
  await expect(navigation.locator('output')).toHaveText('Selected collection: Personal')
  const folders = nav.getByRole('button', { name: 'Folders', exact: true })
  await folders.press('Space')
  await expect(folders).toHaveAttribute('aria-expanded', 'false')
  await expect(personal).toHaveCount(0)
  await folders.press('Enter')
  await expect(personal).toHaveAttribute('aria-current', 'true')
  await expect(nav.locator('ul').first()).toHaveCSS('padding-left', '0px')
  await expect(nav.locator('ul').first()).toHaveCSS('list-style-type', 'none')
  await expect(personal).toHaveCSS('height', '28px')
  await expect(personal).toHaveCSS('border-radius', '5px')
  await expect(personal.locator('svg')).toHaveCSS('width', '16px')
  await expect(folders.locator('svg')).toHaveCSS('width', '11px')

  const groups = page.getByRole('region', { name: 'Sidebar Groups', exact: true })
  const groupNav = groups.getByRole('navigation', { name: 'Grouped notes' })
  const groupFolders = groupNav.getByRole('button', { name: 'Folders', exact: true })
  const favorites = groupNav.getByRole('button', { name: 'Favorites', exact: true })
  await expect(groupFolders).toHaveAttribute('aria-expanded', 'false')
  await expect(favorites).toHaveAttribute('aria-expanded', 'true')
  await groupFolders.click()
  await favorites.click()
  await expect(groupFolders).toHaveAttribute('aria-expanded', 'true')
  await expect(favorites).toHaveAttribute('aria-expanded', 'false')
  await groups.getByRole('tab', { name: 'Code', exact: true }).click()
  await groups.getByRole('button', { name: 'Dark', exact: true }).click()
  await groups.getByRole('tab', { name: 'Preview', exact: true }).click()
  await expect(groupFolders).toHaveAttribute('aria-expanded', 'true')
  await expect(favorites).toHaveAttribute('aria-expanded', 'false')
  await expect(personal).toHaveAttribute('aria-current', 'true')
})

test('shows genuine Sidebar interaction states and preserves selected-row feedback', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: 'light' })
  await page.goto('/?lang=en#/desktop/sidebar')
  const card = page.getByRole('region', { name: 'Sidebar States', exact: true })
  const nav = card.getByRole('navigation')
  const current = nav.getByRole('button', { name: 'Starred', exact: true })
  const all = nav.getByRole('button', { name: 'All Notes', exact: true })
  await current.focus()
  await page.keyboard.press('Tab')
  await expect(all).toBeFocused()
  await expect(all).toHaveCSS('outline-style', 'solid')
  await expect(all).toHaveCSS('outline-width', '2px')
  await all.hover()
  await expect(all).toHaveCSS('background-color', 'rgba(0, 0, 0, 0.05)')
  await page.mouse.down()
  await expect(all).toHaveCSS('background-color', 'rgba(0, 0, 0, 0.1)')
  await page.mouse.move(0, 0)
  await page.mouse.up()
  await all.press('Enter')
  await expect(all).toHaveAttribute('aria-current', 'true')
  await all.hover()
  await expect(all).toHaveCSS('background-color', 'rgba(0, 0, 0, 0.1)')
  await page.mouse.down()
  await expect(all).toHaveCSS('background-color', 'rgba(0, 0, 0, 0.1)')
  await page.mouse.up()
})

test('retains window selection while hiding the sidebar and wrapping at narrow widths', async ({ page }) => {
  await page.goto('/?lang=en#/desktop/sidebar')
  const card = page.getByRole('region', { name: 'Sidebar in Window', exact: true })
  const nav = card.getByRole('navigation', { name: 'Window collections' })
  await expect(nav).toHaveCSS('width', '220px')
  const longName = nav.getByRole('button', { name: 'Research, design references, and project notes' })
  const text = longName.locator('.desktop-sidebar-label')
  expect(await text.evaluate(element => element.scrollWidth > element.clientWidth)).toBe(true)
  await longName.click()
  await expect(card.locator('output')).toHaveText('Selected collection: Research, design references, and project notes')
  await card.getByRole('button', { name: 'Hide sidebar', exact: true }).click()
  await expect(nav).toHaveCount(0)
  await card.getByRole('button', { name: 'Show sidebar', exact: true }).click()
  await expect(longName).toHaveAttribute('aria-current', 'true')
  for (const width of [749, 390]) {
    await page.setViewportSize({ width, height: 852 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    const navigationCard = page.getByRole('region', { name: 'Sidebar Navigation', exact: true })
    await expect(navigationCard.locator('.preview-content')).toHaveCSS('padding-block-start', '160px')
    await expect(navigationCard.getByRole('navigation')).toHaveCSS('width', '220px')
  }
})

test('copies bilingual Sidebar examples and scopes appearance to each card', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await page.addInitScript(() => {
    Object.defineProperty(navigator.clipboard, 'writeText', {
      value: async (source: string) => sessionStorage.setItem('sidebar-source', source),
    })
  })
  await page.goto('/?lang=zh-CN#/desktop/sidebar')
  const nav = page.getByRole('region', { name: '侧边栏导航', exact: true })
  const groups = page.getByRole('region', { name: '侧边栏分组', exact: true })
  await nav.getByRole('button', { name: '个人', exact: true }).click()
  await nav.getByRole('button', { name: '深色', exact: true }).click()
  await expect(nav).toHaveAttribute('data-appearance', 'dark')
  await expect(groups).toHaveAttribute('data-appearance', 'light')
  await expect(page.locator('html')).not.toHaveClass(/dark/)
  await page.getByRole('button', { name: '切换深色', exact: true }).click()
  await nav.getByRole('button', { name: '浅色', exact: true }).click()
  await expect(page.locator('html')).toHaveClass('dark')
  await expect(nav).toHaveAttribute('data-appearance', 'light')
  await expect(groups).toHaveAttribute('data-appearance', 'dark')
  await expect(nav.getByRole('navigation').getByRole('button', { name: '个人' })).toHaveAttribute('aria-current', 'true')

  for (const [locale, titles, codeTab, previewTab, copy] of [
    ['zh-CN', ['侧边栏导航', '侧边栏分组', '侧边栏状态', '窗口中的侧边栏'], '代码', '预览', '复制代码'],
    ['en', ['Sidebar Navigation', 'Sidebar Groups', 'Sidebar States', 'Sidebar in Window'], 'Code', 'Preview', 'Copy code'],
  ] as const) {
    await page.goto('/?lang=' + locale + '#/desktop/sidebar')
    for (const title of titles) {
      const card = page.getByRole('region', { name: title, exact: true })
      await card.getByRole('tab', { name: codeTab, exact: true }).click()
      const code = card.locator('code.language-tsx')
      await expect(code).toContainText("import { useState } from 'react'")
      await expect(code).toContainText('@cgpdesktopui/ui/styles.css')
      await expect(code).not.toContainText('lucide-react')
      const source = await code.textContent()
      await card.getByRole('button', { name: copy, exact: true }).click()
      await expect.poll(() => page.evaluate(() => sessionStorage.getItem('sidebar-source'))).toBe(source)
      await card.getByRole('tab', { name: previewTab, exact: true }).click()
    }
  }
})
